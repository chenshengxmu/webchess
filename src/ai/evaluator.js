const { pieceColor, pieceType, getAllLegalMoves, isInCheck } = require('./rules');

function evaluate(board, difficulty) {
  let score = 0;
  const usePositionTable = difficulty !== 'easy';
  const useMobility = difficulty === 'hard';

  for (let r = 0; r <= 9; r++) {
    for (let c = 0; c <= 8; c++) {
      const piece = board[r][c];
      if (!piece) continue;
      const color = pieceColor(piece);
      const type = pieceType(piece);
      let value = PIECE_VALUES[type] || 0;

      // 兵/卒过河加分
      if (type === 'P') {
        if (color === 'red' && r <= 4) value = 200;
        if (color === 'black' && r >= 5) value = 200;
      }

      // 位置加成
      if (usePositionTable && POSITION_TABLES[type]) {
        const table = POSITION_TABLES[type];
        // 红方使用翻转行（row 9 是底线）
        // 黑方使用正常行（row 0 是底线）
        const tableRow = color === 'red' ? (9 - r) : r;
        const tableCol = color === 'red' ? c : (8 - c);
        value += table[tableRow][tableCol];
      }

      score += color === 'red' ? value : -value;
    }
  }

  // 将军惩罚
  if (isInCheck(board, 'red')) score -= 50;
  if (isInCheck(board, 'black')) score += 50;

  // 困难模式：机动性评估
  if (useMobility) {
    const redMoves = getAllLegalMoves(board, 'red').length;
    const blackMoves = getAllLegalMoves(board, 'black').length;
    score += (redMoves - blackMoves) * 2;
  }

  return score;
}

